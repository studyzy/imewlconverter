    /// <summary>计算 16 位键哈希(输入为词面的 UTF-8 字节)。</summary>
    public static ushort Compute(ReadOnlySpan<byte> data)
    {
        uint h = Seed;
        foreach (var b in data)
            h = T16[(h ^ b) & 0xFF] ^ (h >> 8);
        return (ushort)(h & 0xFFFF);
    }

